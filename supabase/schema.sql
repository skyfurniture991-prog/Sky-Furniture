-- Pesanan -> JSON (camelCase, sama dengan bentuk data pesanan di frontend).
-- Hanya dipanggil dari function lain (tidak dibuka ke publik).
create or replace function public.order_to_json(p_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id',             o.code,
    'uuid',           o.id,
    'createdAt',      (extract(epoch from o.created_at) * 1000)::bigint,
    'status',         o.status,
    'paymentStatus',  o.payment_status,
    'trackingNumber', o.tracking_number,
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'productId', i.product_id, 'slug', i.slug, 'name', i.name, 'image', i.image,
        'options', to_jsonb(i.options), 'qty', i.qty, 'unit', i.unit, 'total', i.total
      ) order by i.id)
      from public.order_items i where i.order_id = o.id and not i.is_bonus
    ), '[]'::jsonb),
    'bonusItems', coalesce((
      select jsonb_agg(jsonb_build_object(
        'productId', i.product_id, 'name', i.name, 'image', i.image, 'qty', i.qty, 'value', i.value
      ) order by i.id)
      from public.order_items i where i.order_id = o.id and i.is_bonus
    ), '[]'::jsonb),
    'customer', jsonb_build_object(
      'name', o.customer_name, 'phone', o.customer_phone, 'email', o.customer_email,
      'address', o.address, 'city', o.city, 'district', o.district, 'province', o.province,
      'postalCode', o.postal_code, 'notes', o.customer_notes, 'workshopNotes', o.workshop_notes
    ),
    'shipping', jsonb_build_object('id', o.shipping_id, 'name', o.shipping_name, 'fee', o.shipping_fee, 'eta', o.shipping_eta),
    'payment',  jsonb_build_object('id', o.payment_id, 'name', o.payment_name),
    'promoCode', o.promo_code,
    'totals', jsonb_build_object(
      'subtotal', o.subtotal, 'discount', o.discount, 'shipping', o.shipping_fee, 'tax', o.tax, 'total', o.total
    ),
    'history', coalesce((
      select jsonb_agg(jsonb_build_object(
        'status', h.status, 'note', h.note, 'at', (extract(epoch from h.created_at) * 1000)::bigint
      ) order by h.created_at, h.id)
      from public.order_status_history h where h.order_id = o.id
    ), '[]'::jsonb)
  )
  from public.orders o
  where o.id = p_id;
$$;

revoke all on function public.order_to_json(uuid) from public, anon, authenticated;

create or replace function public.generate_order_code()
returns text
language plpgsql
as $$
declare
  c text;
begin
  loop
    c := 'SKY-' || to_char(now() at time zone 'Asia/Jakarta', 'YYYYMMDD') || '-'
         || lpad((10000 + floor(random() * 90000))::int::text, 5, '0');
    exit when not exists (select 1 from public.orders where code = c);
  end loop;
  return c;
end;
$$;

revoke all on function public.generate_order_code() from public, anon, authenticated;

-- Membuat pesanan dari checkout. Harga, promo, ongkir, dan pajak dihitung ULANG di server
-- sehingga nilai dari browser tidak dipercaya begitu saja.
--
-- Payload:
-- {
--   "items": [{ "productId": 9, "qty": 1, "material": "Kanvas Linen", "unit": 2785000,
--               "options": ["Biru Langit Azure", "Kanvas Linen", "L-Kiri"] }],
--   "customer": { "name", "phone", "email", "address", "city", "district",
--                 "province", "postalCode", "notes", "workshopNotes" },
--   "shippingId": "direct", "paymentId": "bca", "paymentLabel": "BCA Virtual Account",
--   "promoCode": "SKYBIRU"
-- }
create or replace function public.place_order(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_items     jsonb := coalesce(p_payload -> 'items', '[]'::jsonb);
  v_cust      jsonb := coalesce(p_payload -> 'customer', '{}'::jsonb);
  v_item      jsonb;
  v_prod      public.products%rowtype;
  v_bonus     public.products%rowtype;
  v_ship      public.shipping_methods%rowtype;
  v_pay       public.payment_methods%rowtype;
  v_promo     public.promo_codes%rowtype;
  v_promo_in  text := upper(trim(coalesce(p_payload ->> 'promoCode', '')));
  v_max_qty   int  := setting_num('max_qty', 10)::int;
  v_tax_rate  numeric := setting_num('tax_rate', 0.11);
  v_qty       int;
  v_material  text;
  v_delta     int;
  v_unit      int;
  v_subtotal  int := 0;
  v_discount  int := 0;
  v_shipping  int := 0;
  v_total     int;
  v_tax       int;
  v_order_id  uuid;
  v_label     text;
begin
  if jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 or jsonb_array_length(v_items) > 50 then
    raise exception 'Keranjang kosong atau tidak valid.';
  end if;

  if length(trim(coalesce(v_cust ->> 'name', ''))) < 2
     or length(trim(coalesce(v_cust ->> 'phone', ''))) < 8
     or length(trim(coalesce(v_cust ->> 'address', ''))) < 5 then
    raise exception 'Data pelanggan belum lengkap.';
  end if;

  select * into v_ship from public.shipping_methods
   where id = p_payload ->> 'shippingId' and is_active;
  if not found then
    raise exception 'Metode pengiriman tidak tersedia.';
  end if;

  select * into v_pay from public.payment_methods
   where id = p_payload ->> 'paymentId' and is_active;
  if not found then
    raise exception 'Metode pembayaran tidak tersedia.';
  end if;

  v_label := coalesce(nullif(trim(p_payload ->> 'paymentLabel'), ''), v_pay.name);

  insert into public.orders (
    code, customer_name, customer_phone, customer_email, address, province, city, district,
    postal_code, customer_notes, workshop_notes,
    shipping_id, shipping_name, payment_id, payment_name, promo_code
  ) values (
    public.generate_order_code(),
    left(trim(v_cust ->> 'name'), 120),
    left(trim(v_cust ->> 'phone'), 30),
    left(nullif(trim(coalesce(v_cust ->> 'email', '')), ''), 160),
    left(trim(v_cust ->> 'address'), 500),
    left(nullif(trim(coalesce(v_cust ->> 'province', '')), ''), 60),
    left(nullif(trim(coalesce(v_cust ->> 'city', '')), ''), 80),
    left(nullif(trim(coalesce(v_cust ->> 'district', '')), ''), 80),
    left(nullif(trim(coalesce(v_cust ->> 'postalCode', '')), ''), 12),
    left(nullif(trim(coalesce(v_cust ->> 'notes', '')), ''), 1000),
    left(nullif(trim(coalesce(v_cust ->> 'workshopNotes', '')), ''), 1000),
    v_ship.id, v_ship.name, v_pay.id, left(v_label, 120), nullif(v_promo_in, '')
  )
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(v_items) loop
    select * into v_prod from public.products
     where id = (v_item ->> 'productId')::bigint and is_active;
    if not found then
      raise exception 'Salah satu produk sudah tidak tersedia. Muat ulang halaman lalu coba lagi.';
    end if;

    v_qty := coalesce((v_item ->> 'qty')::int, 0);
    if v_qty < 1 or v_qty > v_max_qty then
      raise exception 'Jumlah pesanan % tidak valid (maks. % unit).', v_prod.name, v_max_qty;
    end if;

    v_material := nullif(trim(coalesce(v_item ->> 'material', '')), '');
    v_delta := 0;
    if cardinality(v_prod.materials) > 0 and v_material is not null then
      if not (v_material = any (v_prod.materials)) then
        raise exception 'Bahan % tidak tersedia untuk %.', v_material, v_prod.name;
      end if;
      v_delta := coalesce((select price from public.materials where name = v_material), 0)
               - coalesce((select price from public.materials where name = v_prod.material), 0);
    end if;
    v_unit := v_prod.price + v_delta;

    if v_item ? 'unit' and (v_item ->> 'unit')::int <> v_unit then
      raise exception 'Harga % telah diperbarui. Muat ulang halaman lalu coba lagi.', v_prod.name;
    end if;

    insert into public.order_items (order_id, product_id, slug, name, image, options, material, qty, unit, total)
    values (
      v_order_id, v_prod.id, v_prod.slug, v_prod.name, v_prod.image,
      array(select jsonb_array_elements_text(coalesce(v_item -> 'options', '[]'::jsonb))),
      v_material, v_qty, v_unit, v_unit * v_qty
    );

    v_subtotal := v_subtotal + v_unit * v_qty;

    if v_prod.bonus_product_id is not null then
      select * into v_bonus from public.products where id = v_prod.bonus_product_id;
      if found then
        insert into public.order_items (order_id, product_id, slug, name, image, qty, unit, total, is_bonus, value)
        values (v_order_id, v_bonus.id, v_bonus.slug, v_bonus.name, v_bonus.image, v_qty, 0, 0, true, v_bonus.price * v_qty);
      end if;
    end if;
  end loop;

  -- Promo
  if v_promo_in <> '' then
    select * into v_promo from public.promo_codes
     where code = v_promo_in
       and is_active
       and (starts_at is null or starts_at <= now())
       and (ends_at is null or ends_at > now())
       and (usage_limit is null or used_count < usage_limit);
    if not found then
      raise exception 'Kode promo % tidak valid atau sudah habis.', v_promo_in;
    end if;
    if v_subtotal < v_promo.min_subtotal then
      raise exception 'Kode promo % berlaku untuk belanja minimal Rp %.', v_promo_in, v_promo.min_subtotal;
    end if;

    if v_promo.type = 'percent' then
      v_discount := least(round(v_subtotal * v_promo.value / 100.0)::int, coalesce(v_promo.max_discount, 2147483647));
    elsif v_promo.type = 'flat' then
      v_discount := least(v_promo.value, v_subtotal);
    end if;

    update public.promo_codes set used_count = used_count + 1 where code = v_promo.code;
  end if;

  -- Ongkir
  v_shipping := v_ship.price;
  if v_promo.type = 'shipping' and v_subtotal >= v_promo.min_subtotal then
    v_shipping := 0;
  elsif v_ship.free_above is not null and v_subtotal >= v_ship.free_above then
    v_shipping := 0;
  end if;

  v_total := greatest(0, v_subtotal - v_discount + v_shipping);
  v_tax   := round(v_total * v_tax_rate / (1 + v_tax_rate))::int;

  update public.orders
     set subtotal     = v_subtotal,
         discount     = v_discount,
         shipping_fee = v_shipping,
         tax          = v_tax,
         total        = v_total,
         shipping_eta = now() + make_interval(days => v_ship.days_max + 3)
   where id = v_order_id;

  return public.order_to_json(v_order_id);
end;
$$;

-- Pelacakan pesanan oleh pelanggan: nomor pesanan + nomor WhatsApp pemesan.
create or replace function public.track_order(p_code text, p_phone text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_phone text;
begin
  select o.id, regexp_replace(o.customer_phone, '\D', '', 'g')
    into v_id, v_phone
    from public.orders o
   where upper(o.code) = upper(trim(coalesce(p_code, '')));

  if v_id is null then
    return null;
  end if;

  if length(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g')) < 8
     or right(v_phone, 9) <> right(regexp_replace(p_phone, '\D', '', 'g'), 9) then
    return null;
  end if;

  return public.order_to_json(v_id);
end;
$$;

