create or replace function public.admin_get_order(p_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak: Hanya admin.';
  end if;
  return public.order_to_json(p_id);
end;
$$;
grant execute on function public.admin_get_order(uuid) to authenticated;


