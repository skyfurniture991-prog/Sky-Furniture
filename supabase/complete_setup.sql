-- Seluruh konten toko dalam satu panggilan (dipakai storefront saat aplikasi dimuat).
create or replace function public.public_content()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'settings',        (select coalesce(jsonb_object_agg(s.key, s.value), '{}'::jsonb) from public.site_settings s),
    'colors',          (select coalesce(jsonb_agg(to_jsonb(c) order by c.sort_order, c.name), '[]'::jsonb) from public.colors c),
    'materials',       (select coalesce(jsonb_agg(to_jsonb(m) order by m.sort_order, m.price), '[]'::jsonb) from public.materials m),
    'categories',      (select coalesce(jsonb_agg(to_jsonb(c) order by c.sort_order, c.name), '[]'::jsonb) from public.categories c where c.is_active),
    'products',        (select coalesce(jsonb_agg(to_jsonb(p) order by p.sort_order, p.id), '[]'::jsonb) from public.products p where p.is_active),
    'reviews',         (select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc, r.id desc), '[]'::jsonb) from public.reviews r where r.is_approved),
    'announcements',   (select coalesce(jsonb_agg(to_jsonb(a) order by a.sort_order, a.id), '[]'::jsonb) from public.announcements a where a.is_active),
    'trust_items',     (select coalesce(jsonb_agg(to_jsonb(t) order by t.sort_order, t.id), '[]'::jsonb) from public.trust_items t where t.is_active),
    'why_us',          (select coalesce(jsonb_agg(to_jsonb(w) order by w.sort_order, w.id), '[]'::jsonb) from public.why_us w where w.is_active),
    'process_steps',   (select coalesce(jsonb_agg(to_jsonb(p) order by p.sort_order, p.id), '[]'::jsonb) from public.process_steps p where p.is_active),
    'faqs',            (select coalesce(jsonb_agg(to_jsonb(f) order by f.sort_order, f.id), '[]'::jsonb) from public.faqs f where f.is_active),
    'home_categories', (select coalesce(jsonb_agg(to_jsonb(h) order by h.sort_order, h.id), '[]'::jsonb) from public.home_categories h where h.is_active),
    'shipping_methods',(select coalesce(jsonb_agg(to_jsonb(s) order by s.sort_order, s.id), '[]'::jsonb) from public.shipping_methods s where s.is_active),
    'payment_methods', (select coalesce(jsonb_agg(to_jsonb(p) order by p.sort_order, p.id), '[]'::jsonb) from public.payment_methods p where p.is_active),
    'promo_codes',     (select coalesce(jsonb_agg(to_jsonb(p) order by p.code), '[]'::jsonb)
                          from public.promo_codes p
                         where p.is_active
                           and (p.starts_at is null or p.starts_at <= now())
                           and (p.ends_at is null or p.ends_at > now())
                           and (p.usage_limit is null or p.used_count < p.usage_limit))
  );
$$;

