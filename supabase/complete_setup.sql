create or replace function public.track_order(p_code text, p_phone text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_phone text;
begin
  select o.id, regexp_replace(o.customer_phone, '\D', '', 'g')
    into v_id, v_phone
    from public.orders o
   where upper(o.code) = upper(trim(coalesce(p_code, '')));

  if v_id is null then
    return null;
  end if;

  if length(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g')) < 8
     or right(v_phone, 9) <> right(regexp_replace(p_phone, '\D', '', 'g'), 9) then
    return null;
  end if;

  return public.order_to_json(v_id);
end;
$$;

