-- Sebelum update: stempel waktu, otomatis maju ke "paid" saat pembayaran diverifikasi,
-- dan catat perubahan status ke riwayat.
create or replace function public.orders_before_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();

  if new.payment_status = 'paid' and old.payment_status is distinct from 'paid' then
    new.paid_at := now();
    if new.status = 'received' then
      new.status := 'paid';
    end if;
  end if;

  if new.status is distinct from old.status then
    insert into public.order_status_history (order_id, status, note, created_by)
    values (new.id, new.status, nullif(trim(coalesce(new.status_note, '')), ''), auth.uid());
  end if;

  new.status_note := null;
  return new;
end;
$$;

drop trigger if exists orders_before_update on public.orders;
create trigger orders_before_update
  before update on public.orders
  for each row execute function public.orders_before_update();

create or replace function public.orders_after_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.order_status_history (order_id, status, note)
  values (new.id, new.status, 'Pesanan dibuat');
  return null;
end;
$$;

drop trigger if exists orders_after_insert on public.orders;
create trigger orders_after_insert
  after insert on public.orders
  for each row execute function public.orders_after_insert();


-- ---------------------------------------------------------------------
-- 6. ROW LEVEL SECURITY
--    - Konten toko: boleh dibaca publik, hanya admin yang boleh mengubah.
--    - Promo, pesanan, dan admin: hanya admin (pelanggan lewat function di bawah).
-- ---------------------------------------------------------------------

do $$
declare
  t text;
begin
  -- Tabel dengan kolom is_active: publik hanya melihat yang aktif
  foreach t in array array[
    'categories', 'products', 'announcements', 'trust_items', 'why_us',
    'process_steps', 'faqs', 'home_categories', 'shipping_methods', 'payment_methods'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "public read" on public.%I', t);
    execute format('create policy "public read" on public.%I for select using (is_active or public.is_admin())', t);
    execute format('drop policy if exists "admin write" on public.%I', t);
    execute format('create policy "admin write" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;

  -- Tabel tanpa is_active: terbaca publik
  foreach t in array array['colors', 'materials', 'site_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "public read" on public.%I', t);
    execute format('create policy "public read" on public.%I for select using (true)', t);
    execute format('drop policy if exists "admin write" on public.%I', t);
    execute format('create policy "admin write" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;

  -- Hanya admin
  foreach t in array array['promo_codes', 'orders', 'order_items', 'order_status_history'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admin all" on public.%I', t);
    execute format('create policy "admin all" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end
$$;

alter table public.reviews enable row level security;
drop policy if exists "public read" on public.reviews;
create policy "public read" on public.reviews for select using (is_approved or public.is_admin());
drop policy if exists "admin write" on public.reviews;
create policy "admin write" on public.reviews for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

alter table public.admins enable row level security;
drop policy if exists "admin read" on public.admins;
create policy "admin read" on public.admins for select to authenticated using (public.is_admin());


